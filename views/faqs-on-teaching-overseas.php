  <h2 style="text-align: center;">FAQs on Teaching Overseas</h2>

  <div>
    <span><strong>1. How do I begin the process of teaching overseas through MwalimuLink?</strong></span>
    <p>
      Once registered on MwalimuLink, you gain two major advantages:
      <br>• Access to a curated directory of over 6,000 international schools, including their direct contact details, at a small subscription fee.
      <br>• Placement opportunities through recruitment agencies that collaborate with MwalimuLink to connect qualified educators to global teaching positions.
      <br><br>Ensure your profile is complete with updated qualifications, teaching experience, a professional photo, and a well-prepared resume.
    </p>
  </div>

  <div>
    <span><strong>2. Who can apply for overseas teaching jobs via MwalimuLink?</strong></span>
    <p>
      Any qualified international teacher — regardless of nationality or residence — can apply if they meet standard teaching requirements.
    </p>
  </div>

  <div>
    <span><strong>3. What are the basic qualifications to teach overseas?</strong></span>
    <p>
      Most schools require:
      <br>• A Bachelor’s degree
      <br>• A teaching license (e.g., PGDE, B.Ed., PGCE)
      <br>• 1–2 years experience
      <br>• Proficiency in English
      <br>• Clean background check
      <br><br>Optional but helpful:
      <br>• ESL/TEFL/TESOL certification
      <br>• IB, Cambridge, or American curriculum experience
    </p>
  </div>

  <div>
    <span><strong>4. Which countries can I teach in through MwalimuLink?</strong></span>
    <p>
      Opportunities exist in the Middle East, Asia, Europe, Africa, South America, and for remote/online platforms.
    </p>
  </div>

  <div>
    <span><strong>5. Can I choose the country I want to teach in?</strong></span>
    <p>
      Yes. You can apply directly to schools or indicate preferences when working with agencies. Flexibility helps.
    </p>
  </div>

  <div>
    <span><strong>6. Are there support services to help me apply or relocate?</strong></span>
    <p>
      Yes. MwalimuLink features agencies and consultants for job matching, interview prep, visa help, and relocation support.
    </p>
  </div>

  <div>
    <span><strong>7. How does the visa process work for teaching abroad?</strong></span>
    <p>
      Most schools sponsor your visa after a job offer. Required documents typically include your passport, certificates, police clearance, and medical checks.
    </p>
  </div>

  <div>
    <span><strong>8. What types of teaching positions are available?</strong></span>
    <p>
      Classroom Teachers, Subject Experts, ESL Instructors, Special Needs Teachers, Curriculum Coordinators, and School Leaders.
    </p>
  </div>

  <div>
    <span><strong>9. What are typical salaries and benefits for international teachers?</strong></span>
    <p>
      Salaries range from $1,000 to $4,000/month depending on the region. Benefits often include housing, flights, insurance, visa support, and bonuses.
    </p>
  </div>

  <div>
    <span><strong>10. Can I relocate with my family?</strong></span>
    <p>
      Yes. Many schools offer family housing, children's education support, or spousal work permits. Disclose your family status when applying.
    </p>
  </div>

  <div>
    <span><strong>11. When should I apply for overseas teaching jobs?</strong></span>
    <p>
      January–May (for August starts) and September–November (for January starts) are peak times. Urgent roles may be posted year-round.
    </p>
  </div>

  <div>
    <span><strong>12. Do I have to pay to apply for jobs?</strong></span>
    <p>
      No. Applying is free. However, there’s a small fee to access the school directory. Be wary of unverified services that charge for guaranteed jobs.
    </p>
  </div>

  <div>
    <span><strong>13. What should I include in my overseas teaching application?</strong></span>
    <p>
      A resume, cover letter, scanned certificates, teaching license, references, passport photo, and sometimes a demo video.
    </p>
  </div>

  <div>
    <span><strong>14. What challenges should I be prepared for?</strong></span>
    <p>
      Cultural adjustment, new curricula, language barriers, legal differences, and homesickness. Join networks and research beforehand.
    </p>
  </div>

  <div>
    <span><strong>15. Is MwalimuLink a recruiting agency?</strong></span>
    <p>
      No. It’s a teacher support platform offering school directories, agency connections, job posts, and community tools.
    </p>
  </div>

  <div>
    <span><strong>16. How does MwalimuLink protect my data?</strong></span>
    <p>
      Your data is shared only with verified partners. You control visibility through your profile settings.
    </p>
  </div>

